export type I18nKey = keyof typeof dict.zh

/** 语言文案查询：t("key") 或 t("key", { name }) */
export function makeT(lang: Lang) {
  return (key: I18nKey, vars?: Record<string, string>): string => {
    const table = dict[lang] ?? dict.zh
    let text = (table[key] ?? dict.zh[key]) as string
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(`{${k}}`, v)
      }
    }
    return text
  }
}

export type T = ReturnType<typeof makeT>

/** i18n Context：子组件无需逐层传 t */
export const TContext = createContext<T>(makeT("zh"))
export function useT(): T {
  return useContext(TContext)
}
